df = pd.DataFrame(data)

# 数据清洗
# 替换"NM"和"#ERROR!"为NaN
df['预期净利润增长率'] = pd.to_numeric(df['预期净利润增长率'], errors='coerce')
df['公允价值上行边际'] = pd.to_numeric(df['公允价值上行边际'], errors='coerce')

# 删除包含NaN的行
df_clean = df.dropna(subset=['公允价值上行边际', '预期净利润增长率'])

# 计算中位数
x_median = df_clean['公允价值上行边际'].median()
y_median = df_clean['预期净利润增长率'].median()
print(f"公允价值上行边际中位数: {x_median:.4f}")
print(f"预期净利润增长率中位数: {y_median:.4f}")

# 定义象限分配函数
def assign_quadrant(row, x_median, y_median):
    if row['公允价值上行边际'] >= x_median and row['预期净利润增长率'] >= y_median:
        return 'Q1 (高公允价值上行，高增长)'
    elif row['公允价值上行边际'] >= x_median and row['预期净利润增长率'] < y_median:
        return 'Q2 (高公允价值上行，低增长)'
    elif row['公允价值上行边际'] < x_median and row['预期净利润增长率'] < y_median:
        return 'Q3 (低公允价值上行，低增长)'
    else:
        return 'Q4 (低公允价值上行，高增长)'

# 分配象限
df_clean['Quadrant'] = df_clean.apply(assign_quadrant, args=(x_median, y_median), axis=1)

# 设置中文字体
plt.rcParams['font.sans-serif'] = ['SimHei']
plt.rcParams['axes.unicode_minus'] = False

# 可视化
plt.figure(figsize=(10, 8))
sns.scatterplot(data=df_clean, x='公允价值上行边际', y='预期净利润增长率', hue='Quadrant', style='Quadrant', s=100)

# 添加中位数分割线
plt.axvline(x=x_median, color='red', linestyle='--', label='公允价值上行边际中位数')
plt.axhline(y=y_median, color='blue', linestyle='--', label='预期净利润增长率中位数')

# 添加数据标签（显示股票名称）
for i, row in df_clean.iterrows():
    plt.text(row['公允价值上行边际'] + 0.01, row['预期净利润增长率'] + 0.05, row['名称'], fontsize=8)

# 设置标题和标签
plt.title('四象限分析：公允价值上行边际 vs 预期净利润增长率')
plt.xlabel('公允价值上行边际')
plt.ylabel('预期净利润增长率 (%)')
plt.legend()
plt.grid(True)
plt.show()


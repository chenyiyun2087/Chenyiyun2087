class TestEvidenceSemanticValidation:
    """Semantic evidence validation gates."""

    def _make_minimal_evidence_dir(self, tmp_path, **overrides):
        """Create a minimal evidence package directory for testing.

        PR20: Creates per-experiment subdirectories (P0/, C0/, A7/, A8/, A9/)
        since flat evidence packages are no longer accepted.
        """
        evidence_dir = tmp_path / "evidence"
        evidence_dir.mkdir()

        # Default: empty files
        defaults = {
            "manifest.json": json.dumps({
                "git_commit_sha": "abc123",
                "worktree_clean": True,
                "config_sha": "sha1",
                "data_sha": "sha2",
                "calendar_sha": "sha3",
                "corporate_action_sha": "sha4",
                "lifecycle_sha": "sha5",
                "python_version": "3.11",
                "dependency_lock_sha": "sha6",
                "evidence_status": "REPRODUCIBLE",
                "promotion_status": "PROMOTION_BLOCKED",
                "files": {},
            }),
            "factor_state_by_fold.json": json.dumps({
                "2025H1": {"status": "NOT_FITTED", "reason": "PR18_matrix_not_run"},
                "2025H2": {"status": "NOT_FITTED", "reason": "PR18_matrix_not_run"},
                "2026H1": {"status": "NOT_FITTED", "reason": "PR18_matrix_not_run"},
            }),
            "corporate_action_snapshot.json": json.dumps({
                "source": "ods_dividend",
                "summary": {"rows": 1000},
                "source_complete": False,
            }),
            "security_lifecycle_snapshot.json": json.dumps({
                "source": "dim_stock",
                "summary": {"rows": 5000},
                "source_complete": False,
            }),
        }

        for name, content in {**defaults, **overrides}.items():
            (evidence_dir / name).write_text(str(content), encoding="utf-8")

        # Create empty parquet files at root level
        for name in ["daily_nav.parquet", "trade_ledger.parquet",
                      "daily_candidates.parquet", "daily_weights.parquet",
                      "daily_exposure.parquet", "rejection_ledger.parquet"]:
            path = evidence_dir / name
            if not path.exists():
                pd.DataFrame().to_parquet(path)

        # PR20: Create per-experiment subdirectories with minimal data
        for exp_id in ["P0", "C0", "A7", "A8", "A9"]:
            exp_dir = evidence_dir / exp_id
            exp_dir.mkdir(exist_ok=True)
            for name in ["daily_nav.parquet", "trade_ledger.parquet",
                          "daily_candidates.parquet", "daily_weights.parquet"]:
                path = exp_dir / name
                if not path.exists():
                    pd.DataFrame().to_parquet(path)

        # Create empty CSV files
        for name in ["random_seed_results.csv", "walk_forward_metrics.csv",
                      "stitched_oos_nav.csv"]:
            path = evidence_dir / name
            if not path.exists():
                path.write_text("seed_id\n" + "\n".join(f"seed_{i}" for i in range(20)))

        # Create remaining required files
        for name in ["git_state.json", "config_snapshot.json", "data_snapshot.json",
                      "calendar_snapshot.json", "fold_definitions.json",
                      "test_log.txt"]:
            path = evidence_dir / name
            if not path.exists():
                path.write_text("{}")

        return evidence_dir

    def test_empty_nav_fails_semantic(self, tmp_path):
        """Empty daily_nav should fail semantic validation."""
        from scripts.research.evidence_semantic import validate_evidence_semantics, SemanticEvidenceStatus

        evidence_dir = self._make_minimal_evidence_dir(tmp_path)
        # NAV is already empty (default)

        report = validate_evidence_semantics(evidence_dir)

class TestAntiLeakageMutation:
    """Future-data leakage detection via mutation testing."""

    def test_pit_slicing_respected(self):
        """Transform should only access data up to signal_date."""
        from scripts.research.alpha_estimator import AlphaEstimator, FittedAlphaState

        estimator = AlphaEstimator()
        state = FittedAlphaState(
            factor_weights={"relative_strength": 0.3, "trend_persistence": 0.2},
            factor_signs={"relative_strength": 1, "trend_persistence": 1},
            train_start="2026-01-02",
            train_end="2026-03-31",
            n_train_days=60,
        )

        # Create proper price data with trade_date column
        dates_a = list(pd.date_range("2026-01-02", periods=10, freq="B"))
        dates_b = list(pd.date_range("2026-01-02", periods=10, freq="B"))
        prices = pd.DataFrame({
            "symbol": ["A"] * 10 + ["B"] * 10,
            "trade_date": dates_a + dates_b,
            "adj_close": (
                list(np.cumprod(1 + np.random.randn(10) * 0.02))
                + list(np.cumprod(1 + np.random.randn(10) * 0.02))
            ),
        })

        # Create scores with trade_date for the signal date
        scores = pd.DataFrame({
            "symbol": ["A", "B"],
            "trade_date": [pd.Timestamp("2026-01-10")] * 2,
            "score": [80.0, 75.0],
            "opt_score": [6.0, 5.0],
            "claude_score": [70.0, 65.0],
        })

        # Signal date is mid-range
        signal_date = "2026-01-10"
        result = estimator.transform(state, signal_date, scores, prices)

        # Result should only contain rows for the signal date
        if not result.empty:
            result_dates = pd.to_datetime(result["trade_date"]).dt.date.unique()
            assert all(d <= pd.Timestamp(signal_date).date() for d in result_dates), (
                "transform() returned data after signal_date — future data leakage!"
            )

    def test_frozen_weights_not_modified(self):
        """FittedAlphaState should be immutable as a frozen dataclass."""
